const isChinese = navigator.languages.some((language) =>
  language.toLowerCase().startsWith("zh"),
);
const messages: Record<MessageKey, string> = isChinese
  ? simplifiedChinese
  : english;

export const editorLanguage = isChinese ? "zh-Hans" : "en";

export function t(
  key: MessageKey,
  replacements: Record<string, string> = {},
): string {
  return Object.entries(replacements).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, value),
    messages[key],
  );
}
